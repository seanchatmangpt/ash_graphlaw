def run(cmd, cwd=REPO):
    p = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True)
    return p.returncode, (p.stdout + (("\n[stderr]\n" + p.stderr) if p.stderr.strip() else "")).strip()

