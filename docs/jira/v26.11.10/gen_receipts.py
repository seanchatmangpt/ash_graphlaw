def run(cmd, cwd=REPO):
    p = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True)
    out = (p.stdout + (("\n[stderr]\n" + p.stderr) if p.stderr.strip() else "")).strip()
    return p.returncode, out

blocks = {}

def cmd_block(label, cmd, note=None, transform=None):
    print(f"[{label}] Running: {' '.join(cmd) if isinstance(cmd, list) else cmd} ...", flush=True)
    rc, out = run(cmd)
    if rc != 0:
        err = f"GATE ASSERTION FAILURE: Gate {label} failed with exit code {rc}!\nCommand: {cmd}\nOutput:\n{out}"
        print(err, file=sys.stderr, flush=True)
        raise RuntimeError(err)
    if transform:
        out = transform(out)
    blocks[label] = (cmd, out, rc, note)
    return rc, out

def extract_test_summary(out):
    lines = out.splitlines()
    summary = []
    for line in lines:
        if line.startswith("Running ExUnit") or line.startswith("Excluding tags:"):
            summary.append(line)
        elif line.startswith("Finished in "):
            if summary and summary[-1] != "":
                summary.append("")
            summary.append(line)
        elif line.startswith("Result: "):
            if summary and summary[-1] != "":
                summary.append("")
            summary.append(line)
    return "\n".join(summary).strip()

